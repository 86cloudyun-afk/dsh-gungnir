#!/usr/bin/env node
// Browser acceptance uses disposable synthetic SQLite data and a fresh Chrome context.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { parseArgs } from 'node:util';
import { startDashboardServer } from '../packages/warroom-dashboard/src/server.js';
import { createDemoSnapshot } from '../packages/warroom-dashboard/src/demo.js';
import { createDashboardSmokeFixture } from './dashboard-smoke-fixture.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({ options: { 'output-dir': { type: 'string' } } });
const output = resolve(values['output-dir'] || join(root, '.superpowers/sdd/dashboard-browser-smoke'));
mkdirSync(output, { recursive: true });
const runtimeRequire = process.env.PLAYWRIGHT_MODULE_ROOT
  ? createRequire(join(resolve(process.env.PLAYWRIGHT_MODULE_ROOT), 'package.json')) : createRequire(import.meta.url);
const { chromium } = runtimeRequire('playwright');
const fixture = createDashboardSmokeFixture();
const before = fixture.hashes();
const result = { fixture: 'temporary synthetic SQLite files; no real home', checks: [], page_errors: [] };
let browser, server, page;
try {
  server = await startDashboardServer({ home: fixture.home, conversationProvider: fixture.conversationProvider, port: 0 });
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome', headless: true });
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => result.page_errors.push(error.message));
  await page.goto(server.url);
  await page.locator('#global-graph [data-node-id]').first().waitFor();
  assert.equal(await page.locator('#global-graph [data-node-id]').count(), fixture.snapshot.nodes.length);
  assert.equal(await page.locator('#messages .message').count(), 0, 'Multiple visible sessions require explicit selection');
  await page.locator('#session-select').selectOption(fixture.sessionIds[0]);
  await page.waitForFunction(() => document.querySelectorAll('#messages .message').length === 4);
  result.checks.push('actual SQLite HTTP snapshot and explicit single-session choice');
  await page.locator('[data-message-id="fixture-route-only"] [data-route-ref]').click();
  assert.match(await page.locator('#breadcrumb').innerText(), /route.*demo-route-02/);
  assert(await page.locator('[data-message-id="fixture-assistant"]').evaluate(element => element.classList.contains('related')), 'Route selection links node-only messages');
  await page.getByRole('button', { name: '刷新快照', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('#data-state').textContent.includes('正在'));
  assert.match(await page.locator('#breadcrumb').innerText(), /route.*demo-route-02/);
  await page.locator('[data-message-id="fixture-task-only"] [data-task-ref]').focus();
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#breadcrumb').innerText(), /task.*fixture-task/);
  await page.getByRole('button', { name: '刷新快照', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('#data-state').textContent.includes('正在'));
  assert.match(await page.locator('#breadcrumb').innerText(), /task.*fixture-task/);
  result.checks.push('route-only/task-only keyboard navigation, reverse linking and refresh retention');
  await page.locator('[data-node-ref]').first().click();
  assert(await page.locator('#focus-graph [data-node-id]').count() > 0);
  assert(await page.locator('.message.related').count() > 0);
  const node = page.locator('#global-graph [data-node-id]').first();
  await page.locator('#fit-map').focus();
  await page.keyboard.press('Tab');
  assert(await node.evaluate(element => element.matches(':focus-visible')), 'SVG keyboard focus is visible');
  await page.keyboard.press('Enter');
  assert.match(await page.locator('#breadcrumb').innerText(), /node/);
  await node.focus();
  await page.keyboard.press('Space');
  result.checks.push('node-to-conversation linking and SVG Enter/Space focus');
  await page.getByRole('button', { name: '折叠证据', exact: true }).click();
  assert.equal(await page.locator('#global-graph [data-node-id="aggregate:evidence"]').count(), 1);
  assert.equal(await page.locator('.route-note').count(), 4);
  assert.match(await page.locator('#focus-anomalies').innerText(), /失败 [1-9]/);
  await page.locator('#global-graph [data-node-id="aggregate:evidence"]').click();
  assert.equal(await page.locator('#global-graph [data-node-id]').count(), 21);
  await page.getByRole('button', { name: '完整图', exact: true }).click();
  assert.equal(await page.locator('.detail-panel').isVisible(), false);
  await page.getByRole('button', { name: '完整图', exact: true }).click();
  const initialView = await page.locator('#global-graph').getAttribute('viewBox');
  await page.getByRole('button', { name: '放大', exact: true }).click();
  assert.notEqual(await page.locator('#global-graph').getAttribute('viewBox'), initialView);
  await page.getByRole('button', { name: '适配全图', exact: true }).click();
  assert.equal(await page.locator('#global-graph').getAttribute('viewBox'), initialView);
  const rect = await page.locator('#global-graph').boundingBox();
  await page.mouse.move(rect.x + 20, rect.y + 25);
  await page.mouse.down();
  await page.mouse.move(rect.x + 70, rect.y + 50);
  await page.mouse.up();
  assert.notEqual(await page.locator('#global-graph').getAttribute('viewBox'), initialView);
  await page.getByRole('button', { name: '适配全图', exact: true }).click();
  await page.locator('#map-search').fill(fixture.snapshot.nodes[0].id);
  await page.getByRole('button', { name: '定位搜索结果', exact: true }).click();
  assert((await page.locator('#breadcrumb').innerText()).includes(fixture.snapshot.nodes[0].id));
  result.checks.push('collapse keeps risk/route notes; full view, zoom, fit, pan and exact-ID search');

  await page.getByRole('button', { name: '显式加载演示数据', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#mode-badge').textContent.includes('synthetic'));
  await page.locator('[data-node-ref]').first().click();
  await page.screenshot({ path: join(output, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Narrow page has no horizontal body overflow');
  assert.equal(await page.locator('.route-note').count(), 4);
  await page.screenshot({ path: join(output, 'mobile.png'), fullPage: true });
  result.checks.push('explicit synthetic demo; desktop and narrow-screen screenshots');
  await page.setViewportSize({ width: 1440, height: 1000 });

  const dto = createDemoSnapshot();
  dto.nodes[0].label = '很长的中文资产名称与证据编号'.repeat(12);
  dto.nodes[1].label = 'ExtremelyLongEnglishAssetIdentifier'.repeat(8);
  dto.nodes[2].label = '<img src=x onerror="window.fixtureXss=1">';
  dto.routes[1].jumphost_id = dto.routes[0].jumphost_id;
  dto.routes[0].lease.state = 'expired';
  dto.routes[0].egress.current = false;
  dto.diagnostics = { ...dto.diagnostics, truncated: true, unresolved_refs: 3, ambiguous_refs: 2, counts: { nodes: 100, edges: 100, routes: 4, tasks: 0 } };
  await page.route('**/api/demo', route => route.fulfill({ json: dto }));
  await page.getByRole('button', { name: '显式加载演示数据', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.map-count-summary')?.textContent.includes('部分图'));
  await page.locator('#map-search').fill(dto.routes[0].jumphost_id);
  await page.getByRole('button', { name: '定位搜索结果', exact: true }).click();
  assert.equal(await page.locator('[data-search-route]').count(), 2);
  await page.locator('[data-search-route]').first().click();
  for (const summary of await page.locator('.map-count-summary').allInnerTexts()) assert.match(summary, /部分图.*\/100.*未解析 3.*歧义 2/);
  assert.match(await page.locator('#focus-anomalies').innerText(), /租约过期 1/);
  const bounded = await page.locator('#global-graph .graph-node').evaluateAll(nodes => nodes.slice(0, 2).every(element => element.querySelector('.node-label').getBBox().width <= Number(element.querySelector('rect').getAttribute('width')) - 38));
  assert(bounded, 'Long labels stay within SVG cards');
  assert.equal(await page.evaluate(() => window.fixtureXss), undefined);
  result.checks.push('partial totals, reference ambiguity, shared-jump choices, expired risk and malicious/long labels');
  await page.unroute('**/api/demo');

  await page.route('**/api/snapshot?*', route => route.fulfill({ status: 503, json: { error: { code: 'E_FIXTURE_UNAVAILABLE' } } }));
  await page.getByRole('button', { name: '返回真实数据', exact: true }).click();
  await page.locator('#global-error').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#global-graph [data-node-id]').count(), 0);
  assert.equal(await page.locator('#messages .message').count(), 0);
  assert.equal(await page.locator('.route-note').count(), 0);
  assert.equal(await page.locator('#focus-anomalies').innerText(), '');
  assert.match(await page.locator('#mode-badge').innerText(), /真实数据.*失败/);
  result.checks.push('real failure clears stale demo/scope data and never fabricates a graph');
  await page.unroute('**/api/snapshot?*');
  const large = createDashboardSmokeFixture({ extraNodes: 240 });
  const largeBefore = large.hashes();
  const largeServer = await startDashboardServer({ home: large.home, port: 0 });
  try {
    await page.goto(largeServer.url);
    await page.waitForFunction(count => document.querySelectorAll('#global-graph [data-node-id]').length === count, large.snapshot.nodes.length);
    assert.equal(large.snapshot.nodes.length, 261);
    assert.equal(await page.locator('#global-graph .graph-edge').count(), large.snapshot.edges.length);
    const extra = large.snapshot.nodes.find(item => item.source_id === 'large-fixture-239');
    await page.locator('#map-search').fill(extra.id);
    await page.getByRole('button', { name: '定位搜索结果', exact: true }).click();
    assert.match(await page.locator('#breadcrumb').innerText(), new RegExp(extra.id));
    await page.getByRole('button', { name: '折叠证据', exact: true }).click();
    assert.equal(await page.locator('.route-note').count(), 4);
    await page.locator('#global-graph [data-node-id="aggregate:evidence"]').click();
    assert.equal(await page.locator('#global-graph [data-node-id]').count(), 261);
    assert.deepEqual(large.hashes(), largeBefore);
    result.checks.push('actual 261-node SQLite graph preserves disconnected evidence, edges and exact search through folding');
  } finally {
    await largeServer.close();
    large.dispose();
  }
  assert.deepEqual(fixture.hashes(), before);
  assert.deepEqual(result.page_errors, []);
  result.checks.push('fact/global database hashes unchanged; zero page errors');
  result.ok = true;
} catch (error) {
  result.ok = false;
  result.error = error.message.slice(0, 700);
  if (page) result.failure_state = await page.evaluate(() => ({ state: document.querySelector('#data-state')?.textContent, error: document.querySelector('#global-error')?.textContent, nodes: document.querySelectorAll('#global-graph [data-node-id]').length }));
} finally {
  await browser?.close();
  await server?.close();
  fixture.dispose();
  writeFileSync(join(output, 'browser-result.json'), JSON.stringify(result, null, 2));
}
console.log(JSON.stringify(result));
process.exitCode = result.ok ? 0 : 1;
